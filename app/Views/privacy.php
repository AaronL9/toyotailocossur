<script>
    // Scrollspy: highlight the active sidebar link as the reader scrolls
    (function() {
        var sections = Array.from(document.querySelectorAll('[id]')).filter(function(el) {
            return document.querySelector('.privacy-nav-link[href="#' + el.id + '"]');
        });
        var links = document.querySelectorAll('.privacy-nav-link');

        function onScroll() {
            var scrollPos = window.scrollY + 160;
            var activeId = sections.length ? sections[0].id : null;
            sections.forEach(function(sec) {
                if (sec.offsetTop <= scrollPos) activeId = sec.id;
            });
            links.forEach(function(link) {
                var isActive = link.getAttribute('href') === '#' + activeId;
                link.classList.toggle('text-red-600', isActive);
                link.classList.toggle('text-gray-600', !isActive);
            });
        }

        window.addEventListener('scroll', onScroll, {
            passive: true
        });
        window.addEventListener('load', onScroll);
    })();
</script>

